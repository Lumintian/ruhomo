/**
 * Runtime-neutral encoding helpers: strict UTF-8, unpadded Base64url and a
 * synchronous SHA-256. They rely only on TextEncoder/TextDecoder, which
 * exist in browsers, Node and Workers. SHA-256 is implemented here so that
 * naming stays synchronous and works outside secure browser contexts.
 */

const encoder = new TextEncoder();

export function utf8Encode(text: string): Uint8Array {
  return encoder.encode(text);
}

export function utf8ByteLength(text: string): number {
  return encoder.encode(text).length;
}

export class Utf8Error extends Error {
  constructor() {
    super('invalid UTF-8');
    this.name = 'Utf8Error';
  }
}

/** Decodes UTF-8 and throws on malformed input instead of inserting U+FFFD. */
export function utf8DecodeStrict(bytes: Uint8Array): string {
  try {
    return new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes);
  } catch {
    throw new Utf8Error();
  }
}

/**
 * True when the JS string is well-formed UTF-16 (no lone surrogates), i.e. it
 * round-trips through UTF-8 unchanged.
 */
export function isWellFormed(text: string): boolean {
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdbff) {
      const n = text.charCodeAt(i + 1);
      if (!(n >= 0xdc00 && n <= 0xdfff)) return false;
      i++;
    } else if (c >= 0xdc00 && c <= 0xdfff) {
      return false;
    }
  }
  return true;
}

const B64URL = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
const B64URL_LOOKUP = (() => {
  const t = new Int16Array(128).fill(-1);
  for (let i = 0; i < B64URL.length; i++) t[B64URL.charCodeAt(i)] = i;
  return t;
})();

export function base64urlEncode(bytes: Uint8Array): string {
  let out = '';
  let i = 0;
  for (; i + 2 < bytes.length; i += 3) {
    const n = (bytes[i]! << 16) | (bytes[i + 1]! << 8) | bytes[i + 2]!;
    out += B64URL[(n >> 18) & 63]! + B64URL[(n >> 12) & 63]! + B64URL[(n >> 6) & 63]! + B64URL[n & 63]!;
  }
  const rest = bytes.length - i;
  if (rest === 1) {
    const n = bytes[i]! << 16;
    out += B64URL[(n >> 18) & 63]! + B64URL[(n >> 12) & 63]!;
  } else if (rest === 2) {
    const n = (bytes[i]! << 16) | (bytes[i + 1]! << 8);
    out += B64URL[(n >> 18) & 63]! + B64URL[(n >> 12) & 63]! + B64URL[(n >> 6) & 63]!;
  }
  return out;
}

export class Base64urlError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'Base64urlError';
  }
}

/**
 * Strict unpadded Base64url decoding. Rejects padding, foreign characters,
 * impossible lengths and non-zero trailing bits, so every byte string has
 * exactly one accepted encoding.
 */
export function base64urlDecode(text: string): Uint8Array {
  if (text.length % 4 === 1) throw new Base64urlError('invalid length');
  const out = new Uint8Array(Math.floor((text.length * 3) / 4));
  let o = 0;
  let acc = 0;
  let bits = 0;
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    const v = code < 128 ? B64URL_LOOKUP[code]! : -1;
    if (v < 0) throw new Base64urlError('invalid character');
    acc = (acc << 6) | v;
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out[o++] = (acc >> bits) & 0xff;
    }
    acc &= (1 << bits) - 1;
  }
  if (acc !== 0) throw new Base64urlError('non-canonical trailing bits');
  return out.subarray(0, o);
}

export function toHex(bytes: Uint8Array): string {
  let s = '';
  for (const b of bytes) s += b.toString(16).padStart(2, '0');
  return s;
}

